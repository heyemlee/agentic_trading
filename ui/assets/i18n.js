  function t(key, vars) {
    let s = (DICT[lang] && DICT[lang][key]);
    if (s === undefined) s = DICT.en[key];
    if (s === undefined) return key;               /* visible, so a gap is obvious */
    if (vars) {
      Object.keys(vars).forEach((k) => {
        s = s.split('{' + k + '}').join(vars[k]);
      });
    }
    return s;
  }

  /* Replace every marked string in the static markup. */
  function applyStatic(root) {
    const r = root || document;
    r.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.getAttribute('data-i18n'));
    });
    r.querySelectorAll('[data-i18n-html]').forEach((el) => {
      el.innerHTML = t(el.getAttribute('data-i18n-html'));
    });
    r.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });
    r.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.placeholder = t(el.getAttribute('data-i18n-ph'));
    });
    document.documentElement.lang = lang === 'zh' ? 'zh-Hans' : 'en';
    const title = document.querySelector('[data-i18n-title]');
    if (title) document.title = t(title.getAttribute('data-i18n-title')) + ' · Agentic Trading';
  }

  function set(next) {
    if (!DICT[next] || next === lang) return;
    lang = next;
    store(() => localStorage.setItem(KEY, next), null);
    applyStatic();
    document.dispatchEvent(new CustomEvent('ct:lang', { detail: { lang: next } }));
  }

  /* Every language's copy of one key, for recognising what someone wrote while
     the console spoke another language. */
  const variants = (key) => Object.keys(DICT).map((l) => DICT[l][key]).filter((s) => s !== undefined);

  return { t, set, applyStatic, variants, LANGS, get lang() { return lang; } };
